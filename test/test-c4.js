// اختبار C4: زرع، حد الشحنات، تفجير عن بُعد، ضرر، اختفاء عند الموت، لقطة الشبكة
import { Game } from '../shared/game.js';
let fails = 0;
const ok = (c, m) => { if (!c) { console.log('  ✗ ' + m); fails++; } else console.log('  ✓ ' + m); };
let T = 1000; const g = new Game(() => T);
const mk = (name) => { const c = { log: [], send(s) { this.log.push(JSON.parse(s)); }, close() {} }; const p = g.connect(c); p.name = name; c.p = p; return c; };
const send = (c, o) => g.onMessage(c.p, JSON.stringify(o));
const step = (sec) => { for (let i = 0; i < sec * 20; i++) { T += 50; g.tick(); } };
const A = mk('A'), B = mk('B');
send(A, { t: 'team', v: 0 }); send(B, { t: 'team', v: 1 });
send(A, { t: 'cfg', map: 0, veh: 0, fill: 0 }); send(A, { t: 'start' }); step(3);
const P = A.p, Q = B.p; P.prot = 0; Q.prot = 0;
P.x = 0; P.z = 0; P.y = 0; Q.x = 3; Q.z = 0; Q.y = 0; Q.hp = 100; P.hp = 100;
ok(P.c4Left === 2, 'شحنتان عند الظهور');
send(A, { t: 'c4', d: [1, -0.4, 0] }); step(1);
ok(g.c4.length === 1 && P.c4Left === 1, 'زُرعت شحنة');
const c = g.c4[0]; ok(Math.hypot(c.x - P.x, c.z - P.z) <= 4.6, `قرب اللاعب (${Math.hypot(c.x - P.x, c.z - P.z).toFixed(1)} م)`);
const snap = [...A.log].reverse().find(m => m.t === 'snap'); ok(snap && Array.isArray(snap.c4) && snap.c4.length === 1, 'تظهر في لقطة الشبكة');
send(A, { t: 'c4', d: [1, -0.4, 0] }); step(1); send(A, { t: 'c4', d: [1, -0.4, 0] }); step(1);
ok(g.c4.length === 2, 'الحد شحنتان');
send(B, { t: 'c4x' }); ok(g.c4.length === 2, 'غير المالك لا يفجّر');
P.x -= 20; Q.x = c.x + 1.5; Q.z = c.z; Q.hp = 100; const nb = A.log.filter(m => m.t === 'boom').length;
send(A, { t: 'c4x' });
ok(g.c4.length === 0 && A.log.filter(m => m.t === 'boom').length > nb, 'فُجّرت عن بُعد وبُثّ الانفجار');
ok(Q.hp < 100 || !Q.alive, `الخصم القريب تأذّى (hp ${Math.round(Q.hp)})`);
// تموت الشحنات بموت صاحبها
step(22); ok(P.c4Left === 2, 'تتجدد الشحنتان بعد 20 ث من التفجير'); P.x = 0; P.z = 0; P.prot = 0; send(A, { t: 'c4', d: [1, -0.5, 0] }); step(1); const had = g.c4.length;
P.prot = 0; g.hurt(P, 500, Q, false, 'x'); step(1); ok(had === 1 && g.c4.length === 0 && !P.alive, 'تختفي بموت صاحبها');
step(8); ok(P.alive && P.c4Left === 2, 'تُجدَّد الشحنات عند الظهور');
console.log(fails ? `فشل ${fails}` : 'نجحت اختبارات C4 ✓'); process.exit(fails ? 1 : 0);
