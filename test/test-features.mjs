// اختبار واجهة المميزات الجديدة: الإعدادات، وضع السيطرة، حزم الإسعاف، الليل، الملف الشخصي
import { createServer } from '../server/server.js';
import { chromium } from 'playwright';
const srv = await createServer(0, '127.0.0.1'); const url = `http://127.0.0.1:${srv.port}/`;
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
let fails = 0; const ok = (c, m) => { console.log((c ? '  ✓ ' : '  ✗ ') + m); if (!c) fails++; };
const errs = [];
const page = await (await browser.newContext({ viewport: { width: 960, height: 540 } })).newPage();
page.on('pageerror', (e) => errs.push(e.message)); page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto(url);
console.log('1) الملف الشخصي والإعدادات');
ok((await page.textContent('#plvl')).includes('مستوى 1'), 'الملف الشخصي يظهر في القائمة');
await page.click('#btnMenuSet'); await page.waitForSelector('#settings:not(.hidden)');
await page.fill('#fov', '90'); await page.selectOption('#xcol', '#6dff8a'); await page.selectOption('#showfps', '0');
await page.click('#btnSetBack'); await page.waitForSelector('#menu:not(.hidden)');
ok(await page.evaluate(() => localStorage.getItem('wz_fov') === '90' && localStorage.getItem('wz_xcol') === '"#6dff8a"'), 'الإعدادات تُحفظ');
await page.fill('#name', 'م'); await page.click('#btnSolo'); await page.waitForSelector('#lobby:not(.hidden)');
await page.click('#btnLobbySet'); await page.waitForSelector('#settings:not(.hidden)'); await page.click('#btnSetBack'); await page.waitForSelector('#lobby:not(.hidden)');
ok(true, 'الإعدادات من اللوبي ترجع إليه');
console.log('2) وضع السيطرة في الليل');
await page.selectOption('#cfgMap', '4'); await page.selectOption('#cfgMode', '1'); await page.selectOption('#cfgTod', '2'); await page.selectOption('#cfgFill', '3'); await page.waitForTimeout(300);
await page.click('#btnStart'); await page.waitForFunction(() => window.__wz.me.alive, null, { timeout: 8000 }); await page.waitForTimeout(1500);
const st = await page.evaluate(() => ({ kits: window.__wz.S.kits.size, zone: !!window.__wz.S.zone, hud: !document.getElementById('zonehud').classList.contains('hidden'), fps: document.getElementById('stat').textContent }));
ok(st.kits >= 2, `حزم الإسعاف وصلت (${st.kits})`); ok(st.zone && st.hud, 'منطقة السيطرة وواجهتها'); ok(st.fps === '', 'إخفاء FPS من الإعدادات');
console.log('3) كاميرا القاتل ومكافآت السلسلة والعلاج');
await page.evaluate(() => { const w = window.__wz; const e = [...w.S.remote.values()].find((r) => r.alive); w.S.__e = e && e.id; });
await page.evaluate(() => { const w = window.__wz; w.me.hp = 30; const k = [...w.S.kits.values()][0]; w.me.x = k.x; w.me.z = k.z; w.me.y = 0; });
await page.waitForTimeout(800);
ok(await page.evaluate(() => window.__wz.me.hp > 30 || [...window.__wz.S.kits.values()].some((k) => !k.up)), 'التقاط حزمة الإسعاف');
await page.evaluate(() => { const w = window.__wz; w.me.alive = false; w.me.killerId = [...w.S.remote.values()].find((r) => r.alive)?.id || 0; });
await page.waitForTimeout(600); ok(true, 'الرسم بكاميرا القاتل بلا أخطاء');
console.log('4) ملف شخصي بعد المباراة');
ok(await page.evaluate(() => JSON.parse(localStorage.getItem('wz_prof') || '{}') !== null), 'الملف محفوظ');
ok(errs.length === 0, 'لا أخطاء في المتصفح ' + errs.join(' | '));
await browser.close(); srv.close && srv.close();
console.log(fails ? `فشل: ${fails}` : 'نجح اختبار المميزات ✓'); process.exit(fails ? 1 : 0);
