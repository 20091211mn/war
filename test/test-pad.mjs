import { createServer } from '../server/server.js';
import { chromium } from 'playwright';
const srv = await createServer(0, '127.0.0.1', { web: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await (await browser.newContext({ viewport: { width: 900, height: 500 } })).newPage();
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.addInitScript(() => { window.__pad = { connected: true, axes: [0, 0, 0, 0], buttons: Array.from({ length: 17 }, () => ({ pressed: false, value: 0 })) }; navigator.getGamepads = () => [window.__pad]; });
await page.goto(`http://127.0.0.1:${srv.port}/`);
await page.fill('#name', 'pad'); await page.click('#btnSolo'); await page.waitForSelector('#lobby:not(.hidden)'); await page.click('#btnStart');
await page.waitForFunction(() => window.__wz.me.alive); await page.waitForTimeout(3500);
const p0 = await page.evaluate(() => ({ x: window.__wz.me.x, z: window.__wz.me.z, yaw: window.__wz.me.yaw }));
await page.evaluate(() => { window.__pad.axes = [0, -1, 0, 0]; });
await page.waitForTimeout(1200);
await page.evaluate(() => { window.__pad.axes = [0, 0, 0, 0]; });
const p1 = await page.evaluate(() => ({ x: window.__wz.me.x, z: window.__wz.me.z, yaw: window.__wz.me.yaw }));
const moved = Math.hypot(p1.x - p0.x, p1.z - p0.z), turned = Math.abs(p1.yaw - p0.yaw);
console.log(`تحرك ${moved.toFixed(1)} م، دار ${turned.toFixed(2)} rad`);
const ok = moved > 1.5 && !errs.length; console.log(ok ? 'نجح اختبار اليد ✓' : 'فشل اختبار اليد ' + errs);
await browser.close(); srv.close(); process.exit(ok ? 0 : 1);
