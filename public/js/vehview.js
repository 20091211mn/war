  part(0, 0.88, 1.55, 1.9, 0.08, 1.9, dark);
  part(-0.96, 1.08, 1.55, 0.08, 0.42, 1.9, body); part(0.96, 1.08, 1.55, 0.08, 0.42, 1.9, body);
